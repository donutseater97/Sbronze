def check_role(password: str) -> str | None:
    """Restituisce il ruolo per una password: 'admin', 'viewer' o None.

    L'admin ha la precedenza: se una password combacia con entrambe (config
    errata), viene trattata come admin.
    """
    if password and ADMIN_PASSWORD and password == ADMIN_PASSWORD:
        return "admin"
    if password and VIEWER_PASSWORD and password == VIEWER_PASSWORD:
        return "viewer"
    return None


def github_get_file_sha(path: str) -> str | None:
    """Recupera lo SHA di un file nel repository GitHub.

    Necessario per aggiornare un file esistente via API.

    Args:
        path: Percorso del file nel repo (es. 'data/funds.csv').

    Returns:
        SHA del file, o None se non trovato / errore.
    """
    if not GITHUB_TOKEN or not GITHUB_REPO:
        return None
    url = f"https://api.github.com/repos/{GITHUB_REPO}/contents/{path}"
    params = {"ref": GITHUB_BRANCH}
    headers = {
        "Authorization": f"Bearer {GITHUB_TOKEN}",
        "Accept": "application/vnd.github+json",
    }
    resp = requests.get(url, headers=headers, params=params, timeout=30)
    if resp.status_code == 200:
        return resp.json().get("sha")
    return None


def github_put_file(path: str, content_str: str, message: str) -> bool:
    """Crea o aggiorna un file nel repository GitHub via API.

    Codifica il contenuto in base64, recupera lo SHA (se il file esiste)
    e invia una richiesta PUT per committare la modifica.

    Args:
        path:        Percorso del file nel repo.
        content_str: Contenuto del file come stringa.
        message:     Messaggio di commit.

    Returns:
        True se il commit è andato a buon fine, False altrimenti.
    """
    if not GITHUB_TOKEN or not GITHUB_REPO:
        return False
    url = f"https://api.github.com/repos/{GITHUB_REPO}/contents/{path}"
    headers = {
        "Authorization": f"Bearer {GITHUB_TOKEN}",
        "Accept": "application/vnd.github+json",
    }
    sha = github_get_file_sha(path)
    data = {
        "message": message,
        "content": base64.b64encode(content_str.encode("utf-8")).decode("ascii"),
        "branch": GITHUB_BRANCH,
    }
    if sha:
        data["sha"] = sha
    resp = requests.put(url, headers=headers, json=data, timeout=30)
    return 200 <= resp.status_code < 300