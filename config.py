@st.cache_data(ttl=300, show_spinner=False)
def load_funds_and_transactions() -> tuple[pd.DataFrame, pd.DataFrame]:
    """Carica fondi e transazioni dai rispettivi file CSV.

    Returns:
        Tupla (funds_df, transactions_df).
        Se i file non esistono, restituisce DataFrame vuoti con le colonne corrette.
    """
    # --- Fondi ---
    if os.path.exists(FUNDS_FILE):
        funds = pd.read_csv(FUNDS_FILE)
    else:
        funds = pd.DataFrame(
            columns=["Fund", "Ticker", "ISIN", "Fund Name", "Type", "Colour"]
        )

    # --- Transazioni ---
    if os.path.exists(TRANSACTIONS_FILE):
        transactions = pd.read_csv(
            TRANSACTIONS_FILE,
            parse_dates=["Date"],
            date_format="%Y-%m-%d %H:%M:%S",
        )
    else:
        transactions = pd.DataFrame(
            columns=["Date", "Fund", "Price (€)", "Quantity", "Fees (€)"]
        )

    return funds, transactions


@st.cache_data(ttl=300, show_spinner=False)
def load_historical_prices(_funds_df: pd.DataFrame) -> pd.DataFrame:
    """Carica i prezzi storici dal file historical_data.csv generato da GitHub Actions.

    Il CSV contiene una colonna 'Date' e una colonna per ogni fondo con il
    nome del ticker. Questa funzione rinomina le colonne ticker → nome fondo
    per coerenza con il resto dell'app.

    Args:
        _funds_df: DataFrame dei fondi (per il mapping Ticker → Fund).

    Returns:
        DataFrame con colonna 'date' (datetime) e una colonna per fondo.
    """
    if not os.path.exists(HISTORICAL_FILE):
        # Diagnostica: mostra il percorso cercato e i file presenti nella directory
        data_dir = os.path.dirname(HISTORICAL_FILE)
        files_in_data = os.listdir(data_dir) if os.path.isdir(data_dir) else ["(directory not found)"]
        st.error(
            f"**{os.path.basename(HISTORICAL_FILE)}** not found.\n\n"
            f"Expected path: `{HISTORICAL_FILE}`\n\n"
            f"Files in `{data_dir}/`: {files_in_data}\n\n"
            f"CWD: `{os.getcwd()}`\n\n"
            "It is generated by GitHub Actions or by running `get_historical_data.py` locally."
        )
        return pd.DataFrame()

    try:
        df = pd.read_csv(HISTORICAL_FILE)
    except Exception as exc:
        st.error(f"Could not read {HISTORICAL_FILE}: {exc}")
        return pd.DataFrame()

    # Normalizza il nome della colonna data
    if "Date" in df.columns:
        df = df.rename(columns={"Date": "date"})

    # Converti la colonna date a datetime (già tz-naive da get_historical_data.py)
    if "date" in df.columns:
        df["date"] = pd.to_datetime(df["date"], errors="coerce")

    # Rinomina colonne ticker → nome fondo (es. "0P0001CRXW.F" → "US")
    for _, row in _funds_df.iterrows():
        ticker = row["Ticker"]
        fund_name = row["Fund"]
        yahoo_col = f"{ticker}.F"
        if yahoo_col in df.columns:
            df = df.rename(columns={yahoo_col: fund_name})

    return df


